#!/usr/bin/env bash
# First-party plugin bundle: build + sign + self-verify.
# (docs/PLUGIN-CHANNEL.md — key model + release flow; CI's release.yml
# `plugin-bundles` job runs THIS script on tag cut, so what ships is
# exactly what was verified here.)
#
# Usage:
#   scripts/first-party-bundle.sh <id> <version> "<notes>" [<min_node>]
#
# Conventions (the plugin family; release.yml passes the same shapes):
#   manifest   crates/<id>-plugin/plugin.toml          (runtime contract)
#   readme     crates/<id>-plugin/bundle-README.md     (staged as README.md)
#   binary     target/release/jerith-<id>              (built if absent)
#   key        keys/plugin-releases.hex                (0600, GITIGNORED)
#   pubkey     keys/plugin-releases.pub                (committed trust anchor)
#   output     dist/<id>-<version>-<os>-<arch>.jbundle (+ .sha256 + .sig)
#
# The verify step runs against a THROWAWAY JERITH_HOME whose pins file
# names the committed pubkey, so a passing run proves the exact chain an
# operator's `jerith plugin install` will run — pinned publisher
# included, never trust-on-first-use.

set -euo pipefail

ROOT="$(cd "$(dirname "$0")/.." && pwd)"
cd "$ROOT"

ID="${1:?usage: first-party-bundle.sh <id> <version> <notes> [min_node]}"
VER="${2:?missing version}"
NOTES="${3:?missing notes}"
MIN_NODE="${4:-$(sed -n 's/^version = "\(.*\)"$/\1/p' Cargo.toml | head -1)}"

BIN_NAME="jerith-${ID}"
BINARY="target/release/${BIN_NAME}"
MANIFEST="crates/${ID}-plugin/plugin.toml"
README_SRC="crates/${ID}-plugin/bundle-README.md"
KEY_FILE="${JERITH_BUNDLE_KEY:-keys/plugin-releases.hex}"
PUB_FILE="keys/plugin-releases.pub"
CLI="${JERITH_CLI:-target/release/jerith}"
OUT="dist/${ID}-${VER}-${OS:-UNSET}-${ARCH:-UNSET}.jbundle"

sha256_portable() {
  if command -v sha256sum >/dev/null 2>&1; then
    sha256sum "$1" | awk '{print $1}'
  else
    shasum -a 256 "$1" | awk '{print $1}'
  fi
}

case "$(uname -s | tr '[:upper:]' '[:lower:]')" in darwin) OS=macos ;; *) OS="$(uname -s | tr '[:upper:]' '[:lower:]')";; esac
case "$(uname -m)" in x86_64|amd64) ARCH=x86_64 ;; aarch64|arm64) ARCH=aarch64 ;; *) ARCH="$(uname -m)" ;; esac
OUT="dist/${ID}-${VER}-${OS}-${ARCH}.jbundle"

[ -f "$MANIFEST" ] || { echo "no manifest at $MANIFEST" >&2; exit 1; }
[ -f "$README_SRC" ] || { echo "no bundle readme at $README_SRC" >&2; exit 1; }
[ -f "$KEY_FILE" ] || {
  echo "no signing key at $KEY_FILE — generate the pair once; keep the hex file 0600 + GITIGNORED, commit ${PUB_FILE}" >&2
  exit 1
}
[ -f "$PUB_FILE" ] || { echo "no committed pubkey at $PUB_FILE" >&2; exit 1; }
[ -x "$CLI" ] || { echo "no CLI at $CLI — cargo build --release -p jerith-mesh-node first" >&2; exit 1; }
if [ ! -x "$BINARY" ]; then
  echo "no plugin binary at $BINARY — building it" >&2
  cargo build --release -p "jerith-${ID}-plugin"
fi

PUB="$(tr -d '[:space:]' < "$PUB_FILE")"
INNER_SHA="$(sha256_portable "$BINARY")"

STAGING="$(mktemp -d)"
cleanup() { rm -rf "$STAGING" "$VERIFY_HOME"; }
VERIFY_HOME="$(mktemp -d)"
trap cleanup EXIT
mkdir "$STAGING/bin"
cp "$MANIFEST" "$STAGING/plugin.toml"
cp "$README_SRC" "$STAGING/README.md"
cp "$BINARY" "$STAGING/bin/$BIN_NAME"
cat > "$STAGING/bundle.toml" <<EOF
# Generated by scripts/first-party-bundle.sh — do not hand-edit the
# sha256/publisher lines; touch anything else only with a version bump.
[bundle]
id = "${ID}"
version = "${VER}"
min_node = "${MIN_NODE}"
os = "${OS}"
arch = "${ARCH}"
binary = "${BIN_NAME}"
binary_sha256 = "${INNER_SHA}"
publisher = "${PUB}"
notes = "${NOTES}"
EOF

mkdir -p dist
"$CLI" plugin build "$STAGING" "$OUT" --key "$KEY_FILE"

# Self-verify against a throwaway home whose pin names the COMMITTED
# pubkey — the operator chain, pinned-publisher path included.
mkdir -p "$VERIFY_HOME/keys"
printf '{"%s": "%s"}\n' "$ID" "$PUB" > "$VERIFY_HOME/keys/plugin-pins.json"
JERITH_HOME="$VERIFY_HOME" "$CLI" plugin verify "$OUT"
echo "sample ok: $OUT (+ .sha256 + .sig under dist/)"

# Channel index (docs/PLUGIN-CHANNEL.md Phase 4): ONLY when the caller
# set --url-base base — a maintainer release cut or the channel-index
# CI job that gathers ALL platforms' rows. The per-platform matrix
# jobs leave it unset so they don't each ship a one-OS index.
if [ -n "${JERITH_CHANNEL_BASE_URL:-}" ]; then
  "$CLI" plugin channel build dist \
    --url-base "$JERITH_CHANNEL_BASE_URL" --key "$KEY_FILE"
  "$CLI" plugin channel verify dist --anchor "$PUB"
  echo "channel ok: dist/channel.json + dist/channel.json.sig"
fi
